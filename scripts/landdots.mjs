import { readFileSync, writeFileSync } from 'node:fs'
import { feature } from 'topojson-client'
import { geoContains } from 'd3-geo'
const topo = JSON.parse(readFileSync('node_modules/world-atlas/land-110m.json','utf8'))
const land = feature(topo, topo.objects.land)
const pts = []
const step = 1.7
for (let lat = -78; lat <= 84; lat += step) {
  const s = step / Math.max(0.25, Math.cos(lat * Math.PI / 180))
  for (let lon = -180; lon < 180; lon += s) {
    if (geoContains(land, [lon, lat])) pts.push([+lat.toFixed(1), +lon.toFixed(1)])
  }
}
writeFileSync('src/data/landDots.ts', `// Generated by scripts/landdots.mjs from Natural Earth (world-atlas). [lat, lon] pairs.\nexport const landDots: number[][] = ${JSON.stringify(pts)}\n`)
console.log(pts.length, 'dots')
